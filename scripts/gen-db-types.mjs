const client = new pg.Client({ connectionString: process.env.PING_TEST_DATABASE_URL });
await client.connect();

const enums = (await client.query(`
  select t.typname as name, array_agg(e.enumlabel::text order by e.enumsortorder) as labels
  from pg_type t join pg_enum e on e.enumtypid = t.oid
  join pg_namespace n on n.oid = t.typnamespace where n.nspname = 'public'
  group by t.typname order by t.typname`)).rows;
const enumNames = new Set(enums.map((e) => e.name));

const cols = (await client.query(`
  select c.table_name, c.column_name, c.is_nullable = 'YES' as nullable,
         c.column_default is not null as has_default,
         c.is_generated = 'ALWAYS' or c.is_identity = 'YES' and c.identity_generation = 'ALWAYS' as generated,
         c.data_type, c.udt_name
  from information_schema.columns c
  join information_schema.tables t on t.table_schema = c.table_schema and t.table_name = c.table_name
  where c.table_schema = 'public' and t.table_type = 'BASE TABLE'
  order by c.table_name, c.ordinal_position`)).rows;
await client.end();

function tsType(udt) {
  const isArray = udt.startsWith("_");
  const base = isArray ? udt.slice(1) : udt;
  let t;
  if (enumNames.has(base)) t = `Database["public"]["Enums"]["${base}"]`;
  else if (["int2", "int4", "int8", "numeric", "float4", "float8"].includes(base)) t = "number";
  else if (base === "bool") t = "boolean";
  else if (["json", "jsonb"].includes(base)) t = "Json";
  else t = "string";
  return isArray ? `${t}[]` : t;
}

