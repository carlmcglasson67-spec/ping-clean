#!/usr/bin/env node
// Writes lib/db/types.ts from the migrated test database, in the same shape as
// `supabase gen types typescript`. Run with: bash scripts/db-test.sh types
// Once a Supabase project exists, `npx supabase gen types typescript --local > lib/db/types.ts`
// produces the official version and can replace this script.
import pg from "pg";
import { writeFileSync } from "node:fs";

const client = new pg.Client({ connectionString: process.env.PING_TEST_DATABASE_URL });
await client.connect();

const enums = (await client.query(`
  select t.typname as name, array_agg(e.enumlabel::text order by e.enumsortorder) as labels
  from pg_type t join pg_enum e on e.enumtypid = t.oid
  join pg_namespace n on n.oid = t.typnamespace where n.nspname = 'public'
  group by t.typname order by t.typname`)).rows;
const enumNames = new Set(enums.map((e) => e.name));

const cols = (await client.query(`
  select c.table_name, c.column_name, c.is_nullable = 'YES' as nullable,
         c.column_default is not null as has_default,
         c.is_generated = 'ALWAYS' or c.is_identity = 'YES' and c.identity_generation = 'ALWAYS' as generated,
         c.data_type, c.udt_name
  from information_schema.columns c
  join information_schema.tables t on t.table_schema = c.table_schema and t.table_name = c.table_name
  where c.table_schema = 'public' and t.table_type = 'BASE TABLE'
  order by c.table_name, c.ordinal_position`)).rows;
await client.end();

function tsType(udt) {
  const isArray = udt.startsWith("_");
  const base = isArray ? udt.slice(1) : udt;
  let t;
  if (enumNames.has(base)) t = `Database["public"]["Enums"]["${base}"]`;
  else if (["int2", "int4", "int8", "numeric", "float4", "float8"].includes(base)) t = "number";
  else if (base === "bool") t = "boolean";
  else if (["json", "jsonb"].includes(base)) t = "Json";
  else t = "string";
  return isArray ? `${t}[]` : t;
}

const tables = {};
for (const c of cols) (tables[c.table_name] ??= []).push(c);

const ind = (n) => "  ".repeat(n);
let out = `// Generated by scripts/gen-db-types.mjs from supabase/migrations. Do not edit by hand.
// Regenerate: bash scripts/db-test.sh types

export type Json = string | number | boolean | null | { [key: string]: Json | undefined } | Json[];

export type Database = {
  public: {
    Tables: {
`;
for (const [name, list] of Object.entries(tables)) {
  out += `${ind(3)}${name}: {\n${ind(4)}Row: {\n`;
  for (const c of list) out += `${ind(5)}${c.column_name}: ${tsType(c.udt_name)}${c.nullable ? " | null" : ""};\n`;
  out += `${ind(4)}};\n${ind(4)}Insert: {\n`;
  for (const c of list) {
    if (c.generated) { out += `${ind(5)}${c.column_name}?: never;\n`; continue; }
    const opt = c.nullable || c.has_default ? "?" : "";
    out += `${ind(5)}${c.column_name}${opt}: ${tsType(c.udt_name)}${c.nullable ? " | null" : ""};\n`;
  }
  out += `${ind(4)}};\n${ind(4)}Update: {\n`;
  for (const c of list) {
    if (c.generated) { out += `${ind(5)}${c.column_name}?: never;\n`; continue; }
    out += `${ind(5)}${c.column_name}?: ${tsType(c.udt_name)}${c.nullable ? " | null" : ""};\n`;
  }
  out += `${ind(4)}};\n${ind(4)}Relationships: [];\n${ind(3)}};\n`;
}
out += `${ind(2)}};
    Views: { [_ in never]: never };
    Functions: {
      public_pricing: {
        Args: Record<PropertyKey, never>;
        Returns: {
          price_per_hour_pence: number | null;
          min_booking_minutes: number | null;
          launch_districts: string[];
          ready: boolean;
        }[];
      };
      apply_as_cleaner: {
        Args: Record<PropertyKey, never>;
        Returns: Database["public"]["Tables"]["cleaners"]["Row"];
      };
      job_board: {
        Args: Record<PropertyKey, never>;
        Returns: {
          offer_id: string;
          series_id: string;
          offered_as: Database["public"]["Enums"]["cleaner_tier"];
          opened_at: string;
          town: string;
          postcode_district: string;
          bedrooms: number;
          bathrooms: number;
          has_pets: boolean;
          frequency: Database["public"]["Enums"]["series_frequency"];
          preferred_day: number;
          window_start: string;
          window_end: string;
          duration_minutes: number;
          starts_on: string;
          earnings_per_visit_pence: number;
          status: Database["public"]["Enums"]["series_status"];
          block_size: number;
          ends_on: string;
          first_refusal: boolean;
        }[];
      };
      claim_series: {
        Args: { p_offer: string };
        Returns: string;
      };
      book_series: {
        Args: {
          p_property: string;
          p_frequency: Database["public"]["Enums"]["series_frequency"];
          p_preferred_day: number;
          p_window_start: string;
          p_window_end: string;
          p_duration_minutes: number;
          p_starts_on: string;
          p_block_size: number;
          p_request_id: string;
        };
        Returns: string;
      };
      admin_end_block: {
        Args: { p_series: string; p_reason: string };
        Returns: undefined;
      };
      start_visit: {
        Args: { p_visit: string };
        Returns: undefined;
      };
      complete_visit: {
        Args: { p_visit: string };
        Returns: undefined;
      };
      admin_assign_series: {
        Args: { p_series: string; p_cleaner: string };
        Returns: undefined;
      };
      admin_reopen_series: {
        Args: { p_series: string };
        Returns: undefined;
      };
    };
    Enums: {
`;
for (const e of enums) out += `${ind(3)}${e.name}: ${e.labels.map((l) => JSON.stringify(l)).join(" | ")};\n`;
out += `${ind(2)}};
    CompositeTypes: { [_ in never]: never };
  };
};

type PublicSchema = Database["public"];
export type Tables<T extends keyof PublicSchema["Tables"]> = PublicSchema["Tables"][T]["Row"];
export type TablesInsert<T extends keyof PublicSchema["Tables"]> = PublicSchema["Tables"][T]["Insert"];
export type TablesUpdate<T extends keyof PublicSchema["Tables"]> = PublicSchema["Tables"][T]["Update"];
export type Enums<T extends keyof PublicSchema["Enums"]> = PublicSchema["Enums"][T];
`;

writeFileSync(new URL("../lib/db/types.ts", import.meta.url), out);
console.log(`lib/db/types.ts: ${Object.keys(tables).length} tables, ${enums.length} enums`);
